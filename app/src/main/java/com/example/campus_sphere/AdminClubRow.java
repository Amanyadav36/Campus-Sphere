package com.example.campus_sphere;

public final class AdminClubRow {
    public final String clubId;
    public final String name;
    public final String handle;
    public final String leaderEmail;

    public AdminClubRow(String clubId, String name, String handle, String leaderEmail) {
        this.clubId = clubId;
        this.name = name;
        this.handle = handle;
        this.leaderEmail = leaderEmail;
    }
}

